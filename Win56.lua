local function refreshPlayers()
    for p, btn in pairs(PlayerButtons) do
        if not Players:FindFirstChild(p.Name) then
            btn:Destroy()
            PlayerButtons[p] = nil
        end
    end
    for _, p in ipairs(Players:GetPlayers()) do
        if p ~= LocalPlayer and not PlayerButtons[p] then
            local btn = Instance.new("TextButton", ListScroll)
            btn.Size = UDim2.new(1, -6, 0, 28)
            btn.Text = " 👤 " .. p.DisplayName
            btn.Font = Enum.Font.Gotham
            btn.TextSize = 11
            btn.TextColor3 = Color3.fromRGB(230, 230, 230)
            btn.TextXAlignment = Enum.TextXAlignment.Left
            Instance.new("UICorner", btn).CornerRadius = UDim.new(0, 4)
            btn.MouseButton1Click:Connect(function()
                CurrentSelectedPlayer = p
                StatusLabel.Text = "เลือก: " .. p.DisplayName
            end)
            PlayerButtons[p] = btn
        end
    end
    ListScroll.CanvasSize = UDim2.new(0, 0, 0, Layout.AbsoluteContentSize.Y)
end

RefreshBtn.MouseButton1Click:Connect(refreshPlayers)
refreshPlayers()
